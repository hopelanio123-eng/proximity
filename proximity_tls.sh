#!/usr/bin/env sh

function die {
    # cleanup to ensure restarting this script doesn't fail because
    # of ports that are still in use
    kill $(jobs -p) > /dev/null 2>&1
    exit $1
}

# generate certificate if it doesn't exist yet
if [ ! -e proximity.pem ]
then
    openssl req -batch -newkey rsa:4096 -sha256 -keyout proximity.key -nodes -x509 -days 365 \
        -subj="/CN=Proximity" -out proximity.crt

    # combine into a pem file as this is everything hitch needs
    cat proximity.key proximity.crt > proximity.pem
    rm proximity.key proximity.crt
fi

# PROXIMITY can be used to determine which version to run.
# If unset, try ./proximity and then proximity from path. If both fail,
# read the path from stdin.
if [ -z "$PROXIMITY" ]
then
    if [ -e proximity ]
    then
        PROXIMITY=./proximity
    else
        if which proximity > /dev/null 2>&1
        then
            PROXIMITY=proximity
        else
            echo "Please specify path to proximity."
            echo -n "> "
            read -r PROXIMITY
        fi
    fi
fi

if [ -z "$ACCESS_CODE" ]
then
    # generate access code if none is given
    ACCESS_CODE="$(openssl rand -base64 12)"
    echo "Autogenerated access code: $ACCESS_CODE"
fi

# cleanup on CTRL+C
trap die SIGINT

# The TLS proxy will be set up as follows: proxy all incoming traffic from
# port 1701 to 1702, where the local Proximity instance is running.

# start Proximity listening only on the local interface
$PROXIMITY --bind-address "127.0.0.1" \
    --web-port "1702" \
    --access-code "$ACCESS_CODE" \
    --no-gui &

# start the proxy
hitch --frontend="[0.0.0.0]:1701" --backend="[127.0.0.1]:1702" \
    --daemon=off --tls-protos="TLSv1.2 TLSv1.3" "proximity.pem" &

wait
